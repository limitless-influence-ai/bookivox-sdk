def render_models_py(schemas: dict[str, Any]) -> str:
    lines: list[str] = [
        '"""Typed models for the Bookivox API (generated)."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Required, TypedDict",
        "",
    ]
    exported: list[str] = []
    for name, schema in schemas.items():
        cls = identifier(name)
        exported.append(cls)
        if is_typed_dict(schema):
            properties, required = merged_object(schema)
            if any(not prop.isidentifier() or keyword.iskeyword(prop) for prop in properties):
                lines.append(f"{cls} = dict[str, Any]")
                lines.extend(["", ""])
                continue
            lines.append(f"class {cls}(TypedDict, total=False):")
            if not properties:
                lines.append("    pass")
            for prop, prop_schema in properties.items():
                prop_type = py_type(prop_schema)
                if prop in required:
                    prop_type = f"Required[{prop_type}]"
                lines.append(f"    {prop}: {prop_type}")
            lines.extend(["", ""])
        else:
            lines.append(f"{cls} = {py_type(schema)}")
            lines.extend(["", ""])
    lines.append("__all__ = [")
    for name in exported:
        lines.append(f'    "{name}",')
    lines.append("]")
    lines.append("")
    return "\n".join([f"# {GENERATED_HEADER.replace(chr(10), chr(10) + '# ')}", ""] + lines)


def split_params(operation: dict[str, Any]) -> tuple[list[dict], list[dict]]:
    path_params: list[dict] = []
    query_params: list[dict] = []
    for param in operation.get("parameters") or []:
        location = param.get("in")
        if location == "header" and str(param.get("name", "")).lower() in IGNORED_HEADER_PARAMS:
            continue
        if location == "path":
            path_params.append(param)
        elif location == "query":
            query_params.append(param)
    return path_params, query_params


def body_schema(operation: dict[str, Any]) -> tuple[dict | None, bool]:
    request_body = operation.get("requestBody") or {}
    content = request_body.get("content") or {}
    schema = (content.get("application/json") or {}).get("schema")
    return schema, bool(request_body.get("required"))


def response_schema(operation: dict[str, Any]) -> dict | None:
    responses = operation.get("responses") or {}
    for code in ("200", "201", "202", "default"):
        response = responses.get(code)
        if not isinstance(response, dict):
            continue
        content = response.get("content") or {}
        schema = (content.get("application/json") or {}).get("schema")
        if schema:
            return schema
    return None


def render_methods_py(operations: list[dict[str, Any]]) -> str:
    lines: list[str] = [
        '"""Typed client methods for the Bookivox API (generated)."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "from urllib.parse import quote",
        "",
        "from .models import *  # noqa: F401,F403",
        "",
        "",
        "class GeneratedMethods:",
        '    """HTTP methods generated from the OpenAPI `x-sdk-method` tags."""',
        "",
    ]
    for item in operations:
        name = snake_case(item["name"])
        operation = item["operation"]
        path_params, query_params = split_params(operation)
        body, body_required = body_schema(operation)
        returns = response_schema(operation)

        signature: list[str] = ["self"]
        for param in path_params:
            signature.append(f"{identifier(param['name'])}: {py_type(param.get('schema'))}")
        if body is not None:
            body_type = py_type(body)
            signature.append(
                f"body: {body_type}"
                if body_required
                else f"body: {optional_py(body_type)} = None"
            )
        if query_params:
            signature.append("*")
            for param in query_params:
                param_type = py_type(param.get("schema"))
                if param.get("required"):
                    signature.append(f"{identifier(param['name'])}: {param_type}")
                else:
                    signature.append(
                        f"{identifier(param['name'])}: {optional_py(param_type)} = None"
                    )

        return_type = py_type(returns) if returns else "Any"
        description = docstring(
            operation.get("x-sdk-description") or operation.get("summary") or ""
        )
        lines.append(f"    def {name}({', '.join(signature)}) -> {return_type}:")
        if description:
            lines.append(f'        """{description}"""')

        url = re.sub(
            r"\{([^}]+)\}",
            lambda match: "{quote(str(%s), safe='')}" % identifier(match.group(1)),
            item["path"],
        )
        if "{" in item["path"]:
            url_literal = f'f"{url}"'
        else:
            url_literal = f'"{url}"'

        call: list[str] = [
            "        return self._request(",
            f'            "{item["http_method"]}",',
            f"            {url_literal},",
        ]
        if query_params:
            call.append("            params={")
            for param in query_params:
                call.append(f'                "{param["name"]}": {identifier(param["name"])},')
            call.append("            },")
        if body is not None:
            call.append("            json_body=body,")
        call.append("        )")
        lines.extend(call)
        lines.append("")
    return "\n".join([f"# {GENERATED_HEADER.replace(chr(10), chr(10) + '# ')}", ""] + lines)


