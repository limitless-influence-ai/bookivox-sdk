def render_types_ts(schemas: dict[str, Any]) -> str:
    lines: list[str] = [
        "/** Typed models for the Bookivox API (generated). */",
        "",
    ]
    for name, schema in schemas.items():
        if is_typed_dict(schema):
            properties, required = merged_object(schema)
            lines.append(f"export interface {name} {{")
            for prop, prop_schema in properties.items():
                key = prop if prop.isidentifier() else f'"{prop}"'
                optional = "" if prop in required else "?"
                lines.append(f"  {key}{optional}: {ts_type(prop_schema)};")
            lines.append("}")
            lines.append("")
        else:
            lines.append(f"export type {name} = {ts_type(schema)};")
            lines.append("")
    return "\n".join([f"/* {GENERATED_HEADER.replace(chr(10), chr(10) + ' ')} */", ""] + lines)


def render_methods_ts(operations: list[dict[str, Any]], schemas: dict[str, Any]) -> str:
    known_types = set(schemas)
    used_types: set[str] = set()

    def track(type_expr: str) -> str:
        for token in re.findall(r"[A-Za-z_][A-Za-z0-9_]*", type_expr):
            if token in known_types:
                used_types.add(token)
        return type_expr

    body_lines: list[str] = []
    for item in operations:
        method_name = camel_case(item["name"])
        operation = item["operation"]
        path_params, query_params = split_params(operation)
        body, body_required = body_schema(operation)
        returns = response_schema(operation)
        return_type = track(ts_type(returns) if returns else "unknown")

        signature: list[str] = []
        for param in path_params:
            signature.append(
                f"{camel_case(param['name'])}: {track(ts_type(param.get('schema')))}"
            )
        if body is not None:
            body_type = track(ts_type(body))
            signature.append(f"body: {body_type}" if body_required else f"body?: {body_type}")
        if query_params:
            fields = " ".join(
                f"{camel_case(param['name'])}{'' if param.get('required') else '?'}: "
                f"{track(ts_type(param.get('schema')))};"
                for param in query_params
            )
            optional = "" if any(param.get("required") for param in query_params) else "?"
            signature.append(f"options{optional}: {{ {fields} }}")

        url = re.sub(
            r"\{([^}]+)\}",
            lambda match: "${encodeURIComponent(String(%s))}" % camel_case(match.group(1)),
            item["path"],
        )
        url_literal = f"`{url}`"

        description = docstring(
            operation.get("x-sdk-description") or operation.get("summary") or ""
        )
        if description:
            body_lines.append(f"  /** {description} */")
        body_lines.append(
            f"  {method_name}({', '.join(signature)}): Promise<{return_type}> {{"
        )
        request_args = [f'"{item["http_method"]}"', url_literal]
        if query_params or body is not None:
            options: list[str] = []
            if query_params:
                pairs = ", ".join(
                    f"{camel_case(param['name'])}: options?.{camel_case(param['name'])}"
                    for param in query_params
                )
                options.append(f"query: {{ {pairs} }}")
            if body is not None:
                options.append("body")
            request_args.append(f"{{ {', '.join(options)} }}")
        body_lines.append(
            f"    return this.request<{return_type}>({', '.join(request_args)});"
        )
        body_lines.append("  }")

    lines: list[str] = [
        "/** Typed client methods for the Bookivox API (generated). */",
        "",
    ]
    if used_types:
        names = ", ".join(sorted(used_types))
        lines.append(f'import type {{ {names} }} from "./types.js";')
        lines.append("")
    lines.extend(
        [
            'import type { RequestOptions } from "./client.js";',
            "",
            "export abstract class GeneratedMethods {",
            "  protected abstract request<T>(",
            "    method: string,",
            "    path: string,",
            "    options?: RequestOptions,",
            "  ): Promise<T>;",
            "",
        ]
    )
    lines.extend(body_lines)
    lines.append("}")
    lines.append("")
    return "\n".join([f"/* {GENERATED_HEADER.replace(chr(10), chr(10) + ' ')} */", ""] + lines)


# ---------------------------------------------------------------------------
# Filtered contract
# ---------------------------------------------------------------------------


def render_sdk_spec(spec: dict[str, Any], operations: list[dict[str, Any]], schemas: dict[str, Any]) -> str:
    paths: dict[str, Any] = {}
    for item in operations:
        paths.setdefault(item["path"], {})[item["http_method"].lower()] = item["operation"]

    servers = [
        {"url": "https://api.bookivox.com", "description": "Production"},
        {"url": "http://localhost:8000", "description": "Local development"},
    ]
    filtered = {
        "openapi": spec.get("openapi", "3.1.0"),
        "info": {
            "title": "Bookivox SDK API",
            "description": (
                "Public contract consumed by the Bookivox SDKs. Contains only the "
                "operations tagged with `x-sdk-method`."
            ),
            "version": (spec.get("info") or {}).get("version", "0.0.0"),
        },
        "servers": servers,
        "paths": dict(sorted(paths.items())),
        "components": {"schemas": schemas},
    }
    return json.dumps(filtered, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

OUTPUTS = {
    "openapi.sdk.json": "spec",
    "python/src/bookivox_sdk/models.py": "models_py",
    "python/src/bookivox_sdk/_generated.py": "methods_py",
    "typescript/src/types.ts": "types_ts",
    "typescript/src/generated.ts": "methods_ts",
}


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Bookivox SDKs from OpenAPI.")
    parser.add_argument("--spec", help="Path to an OpenAPI JSON file (defaults to the live API).")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit 1 if any generated file is out of date.",
    )
    args = parser.parse_args()

    if args.check and args.spec is None:
        # Verification must not depend on a running API: re-render the committed
        # contract and compare the result with the committed outputs.
        spec = load_spec(str(SDK_ROOT / "openapi.sdk.json"))
    else:
        spec = load_spec(args.spec)
    operations = sdk_operations(spec)
    if not operations:
        print("No operation tagged with 'x-sdk-method'. Nothing to generate.", file=sys.stderr)
        return 1
    schemas = reachable_schemas(spec, operations)

    rendered = {
        "spec": render_sdk_spec(spec, operations, schemas),
        "models_py": render_models_py(schemas),
        "methods_py": render_methods_py(operations),
        "types_ts": render_types_ts(schemas),
        "methods_ts": render_methods_ts(operations, schemas),
    }

    stale: list[str] = []
    for relative, key in OUTPUTS.items():
        target = SDK_ROOT / relative
        content = rendered[key]
        if args.check:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != content:
                stale.append(relative)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("Out of date (run sdk/generate_sdk.sh):", file=sys.stderr)
            for name in stale:
                print(f"  - {name}", file=sys.stderr)
            return 1
        print(f"SDK up to date ({len(operations)} operations, {len(schemas)} models).")
        return 0

    print(
        f"Generated {len(OUTPUTS)} files | {len(operations)} operations | {len(schemas)} models"
    )
    for item in operations:
        print(f"  - {item['name']:<20} {item['http_method']:<6} {item['path']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
