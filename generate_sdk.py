#!/usr/bin/env python3
"""Generate the Bookivox SDKs from the live API OpenAPI schema.

Single source of truth: the running API's OpenAPI document. Only operations
tagged with ``x-sdk-method`` (see ``api/sdk_expose.py``) are exposed, so the
SDK surface stays small and auditable. Everything else is invisible.

Outputs (all auto-generated, never edit by hand):

    sdk/openapi.sdk.json                          filtered public contract
    sdk/python/src/bookivox_sdk/models.py         TypedDict models
    sdk/python/src/bookivox_sdk/_generated.py     typed client methods
    sdk/typescript/src/types.ts                   TypeScript interfaces
    sdk/typescript/src/generated.ts               typed client methods

Usage:
    ./generate_sdk.sh                       # fetch from BOOKIVOX_OPENAPI_URL
    ./generate_sdk.sh --spec ./openapi.json  # use a local schema file
    ./generate_sdk.sh --check               # CI: fail if generated files drift
                                             # (offline: re-renders from the
                                             # committed openapi.sdk.json)

The generator only uses the standard library so it can run anywhere.
"""

from __future__ import annotations

import argparse
import json
import keyword
import os
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

SDK_ROOT = Path(__file__).resolve().parent
DEFAULT_OPENAPI_URL = "http://127.0.0.1:8000/api/v1/openapi.json"
SDK_TAG = "x-sdk-method"
IGNORED_HEADER_PARAMS = {"authorization", "x-api-key"}
GENERATED_HEADER = (
    "AUTO-GENERATED by sdk/generate_sdk.py — DO NOT EDIT.\n"
    "Run `sdk/generate_sdk.sh` to refresh from the live OpenAPI schema."
)

# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


def load_spec(spec_path: str | None) -> dict[str, Any]:
    if spec_path:
        return json.loads(Path(spec_path).read_text(encoding="utf-8"))
    url = os.environ.get("BOOKIVOX_OPENAPI_URL", DEFAULT_OPENAPI_URL)
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed scheme+host from env
        return json.loads(response.read().decode("utf-8"))


def sdk_operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    operations: list[dict[str, Any]] = []
    for path, methods in spec.get("paths", {}).items():
        for http_method, operation in methods.items():
            if not isinstance(operation, dict):
                continue
            name = operation.get(SDK_TAG)
            if not name:
                continue
            operations.append(
                {
                    "name": name,
                    "http_method": http_method.upper(),
                    "path": path,
                    "operation": operation,
                }
            )
    operations.sort(key=lambda item: item["name"])
    return operations


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def collect_refs(node: Any, acc: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            acc.add(ref_name(ref))
        for value in node.values():
            collect_refs(value, acc)
    elif isinstance(node, list):
        for value in node:
            collect_refs(value, acc)


def reachable_schemas(spec: dict[str, Any], operations: list[dict[str, Any]]) -> dict[str, Any]:
    components = spec.get("components", {}).get("schemas", {})
    pending: set[str] = set()
    collect_refs([op["operation"] for op in operations], pending)
    resolved: set[str] = set()
    stack = list(pending)
    while stack:
        name = stack.pop()
        if name in resolved or name not in components:
            continue
        resolved.add(name)
        nested: set[str] = set()
        collect_refs(components[name], nested)
        stack.extend(nested - resolved)
    return {name: components[name] for name in sorted(resolved)}


# ---------------------------------------------------------------------------
# Schema helpers
# ---------------------------------------------------------------------------


def merged_object(schema: dict[str, Any]) -> tuple[dict[str, Any], set[str]]:
    """Flatten allOf and return (properties, required)."""
    properties: dict[str, Any] = dict(schema.get("properties") or {})
    required = set(schema.get("required") or [])
    for part in schema.get("allOf") or []:
        sub_props, sub_required = merged_object(part)
        properties.update(sub_props)
        required |= sub_required
    return properties, required


def is_typed_dict(schema: dict[str, Any]) -> bool:
    if schema.get("type") == "array":
        return False
    properties, _ = merged_object(schema)
    return bool(properties)


def py_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "Any"
    if "$ref" in schema:
        return identifier(ref_name(schema["$ref"]))
    variants = schema.get("anyOf") or schema.get("oneOf")
    if variants:
        nullable = any(variant.get("type") == "null" for variant in variants)
        parts = [py_type(variant) for variant in variants if variant.get("type") != "null"]
        unique = list(dict.fromkeys(parts)) or ["Any"]
        result = " | ".join(unique)
        if nullable or schema.get("nullable"):
            result += " | None"
        return dedupe_union(result)
    schema_type = schema.get("type")
    if schema_type == "array":
        return f"list[{py_type(schema.get('items'))}]"
    if schema_type == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            result = f"dict[str, {py_type(additional)}]"
        elif isinstance(additional, bool) and additional:
            result = "dict[str, Any]"
        else:
            result = "dict[str, Any]"
        return f"{result} | None" if schema.get("nullable") else result
    primitive = {
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "string": "str",
        "null": "None",
    }.get(schema_type, "Any")
    return f"{primitive} | None" if schema.get("nullable") and primitive != "None" else primitive


def ts_type(schema: dict[str, Any] | None, indent: int = 0) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    variants = schema.get("anyOf") or schema.get("oneOf")
    if variants:
        nullable = any(variant.get("type") == "null" for variant in variants)
        parts = [ts_type(variant) for variant in variants if variant.get("type") != "null"]
        unique = list(dict.fromkeys(parts)) or ["unknown"]
        result = " | ".join(unique)
        if nullable or schema.get("nullable"):
            result += " | null"
        return dedupe_union(result)
    schema_type = schema.get("type")
    if schema_type == "array":
        item = ts_type(schema.get("items"))
        result = f"({item})[]" if "|" in item else f"{item}[]"
        return f"{result} | null" if schema.get("nullable") else result
    if schema_type == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            result = f"Record<string, {ts_type(additional)}>"
        else:
            result = "Record<string, unknown>"
        return f"{result} | null" if schema.get("nullable") else result
    primitive = {
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "string": "string",
        "null": "null",
    }.get(schema_type, "unknown")
    return f"{primitive} | null" if schema.get("nullable") and primitive != "null" else primitive


def identifier(name: str) -> str:
    cleaned = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    return cleaned


def dedupe_union(type_expr: str) -> str:
    parts: list[str] = []
    for part in (segment.strip() for segment in type_expr.split("|")):
        if part and part not in parts:
            parts.append(part)
    return " | ".join(parts)


def optional_py(py: str) -> str:
    return dedupe_union(f"{py} | None")


def camel_case(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(part.capitalize() for part in parts[1:])


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def docstring(text: str) -> str:
    cleaned = (text or "").replace("\\", "\\\\").replace('"""', "'''").strip()
    return cleaned


